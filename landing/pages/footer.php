<script>
/* Redressement des titres de section.
   Ici plutot que dans vitrine.js : la barre et le pied sont partages par la
   page unique ET les cinq pages autonomes, qui ne chargent pas ce script.
   Sans observateur, la classe n'arriverait jamais et les titres resteraient
   inclines — l'effet doit donc echouer en position lisible, pas l'inverse. */
(function () {
    var titres = document.querySelectorAll('.section-title');
    if (!titres.length) { return; }

    var moins = window.matchMedia
        && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    // Pas d'observateur disponible, ou mouvement reduit : on affiche a plat.
    if (moins || !('IntersectionObserver' in window)) {
        Array.prototype.forEach.call(titres, function (t) { t.classList.add('est-vu'); });
        return;
    }

    var obs = new IntersectionObserver(function (entrees) {
        entrees.forEach(function (e) {
            if (!e.isIntersecting) { return; }
            e.target.classList.add('est-vu');
            obs.unobserve(e.target);      // une fois redresse, il le reste
        });
    }, { rootMargin: '0px 0px -12% 0px' });

    Array.prototype.forEach.call(titres, function (t) { obs.observe(t); });
})();
</script>

