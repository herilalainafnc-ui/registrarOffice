<script>
/* =============================================================================
   Retour en haut

   Le bouton n'apparait qu'une fois le hero passe : proposer de remonter alors
   qu'on s'y trouve deja n'aurait aucun sens.

   Le seuil est la hauteur du hero quand il existe — c'est le moment ou l'on
   quitte vraiment le haut de la page — et un demi-ecran sur les pages
   autonomes, qui n'en ont pas.

   L'ecoute du defilement est passive et n'y fait rien d'autre que comparer
   deux nombres : le calcul de position, lui, est fait une fois au chargement
   et aux redimensionnements, pas a chaque pixel parcouru.
   ========================================================================== */
(function () {
    var bouton = document.getElementById('haut-page');
    if (!bouton) { return; }

    var hero = document.getElementById('accueil');
    var seuil = 0;

    function mesurer() {
        seuil = hero
            ? Math.max(240, hero.offsetHeight * 0.75)
            : Math.max(240, window.innerHeight * 0.5);
    }

    function ajuster() {
        var doitParaitre = window.scrollY > seuil;
        if (doitParaitre === !bouton.hidden) { return; }   // rien a changer
        bouton.hidden = !doitParaitre;
    }

    bouton.addEventListener('click', function () {
        var moinsDeMouvement = window.matchMedia
            && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

        /* On vise le hero quand il existe, le haut du document sinon. Et l'on
           passe par scrollTo plutot que par une ancre : changer le fragment de
           l'URL laisserait « #accueil » dans la barre d'adresse, que le
           visiteur n'a pas demande. */
        var cible = hero ? hero.offsetTop : 0;
        window.scrollTo({
            top: cible,
            behavior: moinsDeMouvement ? 'auto' : 'smooth'
        });

        /* Le focus revient en tete de page : sans cela, la tabulation
           reprendrait depuis le bouton, donc depuis le bas — on remonte a
           l'ecran mais pas au clavier. */
        var premier = document.querySelector('.nav-logo, .navbar a, header a');
        if (premier && premier.focus) { premier.focus({ preventScroll: true }); }
    });

    mesurer();
    ajuster();
    window.addEventListener('scroll', ajuster, { passive: true });
    window.addEventListener('resize', function () { mesurer(); ajuster(); });
})();
</script>

